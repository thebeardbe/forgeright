/**
 * Store locations and path safety.
 *
 * An organisation id reaches the store from a session cookie and from URL parameters, so it is
 * validated as one path component before being joined into a filename, and the file it names must be
 * a regular file inside the store directory rather than a symlink that looks like one.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Repository root, two levels up from lib/store. */
const PROJECT_ROOT = path.join(__dirname, '..', '..');

/** Default store location, overridable with STORE_DIR so a volume can be mounted. */
const DEFAULT_STORE_DIR = path.join(PROJECT_ROOT, 'data', 'store');

/** Subdirectory holding one database file per organisation. */
const ORGS_DIRNAME = 'orgs';

/** Suffix of an organisation database file. */
const DB_SUFFIX = '.db';

/**
 * File name of the installation database, directly under the store directory. A literal this module
 * constructs and never a value from a request, which is what makes it safe to join to storeDir()
 * without an id-validation step.
 */
const ADMIN_DB_NAME = 'admin.db';

/**
 * Organisation ids are generated by this system: lowercase letters, digits and hyphens, 1 to 64
 * characters, starting with a letter or digit. That excludes "." and ".." and every path separator,
 * so an id cannot escape the orgs directory by name.
 */
const ORG_ID_PATTERN = /^[a-z0-9][a-z0-9-]{0,63}$/;

/**
 * @returns {string} Absolute path of the store root.
 */
export function storeDir() {
    return process.env.STORE_DIR || DEFAULT_STORE_DIR;
}

/**
 * Validates an organisation id as a single safe path component, which stops traversal in a name
 * ("../../etc/passwd"). It says nothing about what the resulting path points at, which is
 * assertOpenableDatabaseFile's job.
 *
 * @param {unknown} orgId
 * @returns {string} The id, unchanged, when it is safe.
 * @throws {Error} Naming the offending value when it is not.
 */
export function assertSafeOrgId(orgId) {
    if (typeof orgId !== 'string' || !ORG_ID_PATTERN.test(orgId)) {
        throw new Error(
            `Unsafe organisation id: ${JSON.stringify(orgId)}. ` +
            `Expected lowercase letters, digits and hyphens, 1 to 64 characters.`
        );
    }
    return orgId;
}

/**
 * The directory holding one database file per organisation, resolved once and cached, so a
 * `STORE_DIR/orgs` that is itself a symlink is resolved a single time and every later operation uses
 * that real path. Resolving per call would follow a redirect that could be changed between calls.
 *
 * @returns {string}
 */
let resolvedOrgsDir = null;

export function orgsDirectoryPath() {
    if (resolvedOrgsDir !== null) return resolvedOrgsDir;

    const candidate = path.join(storeDir(), ORGS_DIRNAME);
    fs.mkdirSync(candidate, { recursive: true });

    resolvedOrgsDir = fs.realpathSync(candidate);
    return resolvedOrgsDir;
}

/**
 * Asserts that the orgs directory is still the directory resolved at startup. A symlinked orgs
 * directory at startup is legitimate, a mounted volume, so it is resolved and the target used, and
 * this compares against the cached resolved path; the directory being replaced after resolution is
 * an attack or a serious operator error and must not silently redirect writes outside the store.
 *
 * `realpathSync` follows a new symlink and returns a different path, so the comparison fails; before
 * any swap it returns the cached path whatever symlinks are legitimately in place. It runs once per
 * connection open rather than per query, because that is where a swap takes effect.
 *
 * @throws {Error} When the orgs directory no longer resolves to the path that was first resolved.
 */
export function assertOrgsDirectoryUnchanged() {
    if (resolvedOrgsDir === null) {
        // Not resolved yet; the first resolution establishes the baseline.
        orgsDirectoryPath();
        return;
    }

    const candidate = path.join(storeDir(), ORGS_DIRNAME);
    let current;
    try {
        current = fs.realpathSync(candidate);
    } catch (err) {
        throw new Error(
            `The store directory ${candidate} can no longer be resolved (${err.code || err.message}). ` +
            `It was ${resolvedOrgsDir} when the store started. Refusing to open a database.`
        );
    }

    if (current !== resolvedOrgsDir) {
        console.error(
            `[store] refusing to open a database: ${candidate} now resolves to ${current}, ` +
            `but it resolved to ${resolvedOrgsDir} when the store started.`
        );
        throw new Error(
            `The store directory changed underneath the store: ${candidate} now resolves to ${current}, ` +
            `but resolved to ${resolvedOrgsDir} at startup. A mounted store is resolved once and used from ` +
            `that path; refusing to write, because following the new target would place data outside the store.`
        );
    }
}

/** Test helper: forget the resolved directories, after changing STORE_DIR. */
export function resetResolvedPaths() {
    resolvedOrgsDir = null;
    resolvedStoreDir = null;
}

/**
 * Absolute path of one organisation's database file, which the caller must pass through
 * assertOpenableDatabaseFile before opening, because this function only guarantees the name is safe:
 * a symlink called <legalOrgId>.db satisfies every check on a string while pointing at another
 * organisation's data.
 *
 * @param {string} orgId
 * @returns {string}
 */
export function orgDbPath(orgId) {
    const safeId = assertSafeOrgId(orgId);
    const dir = orgsDirectoryPath();
    const fullPath = path.join(dir, `${safeId}${DB_SUFFIX}`);

    // Containment by name, deliberately lexical: it catches a name, while
    // assertOpenableDatabaseFile catches a file.
    if (path.dirname(fullPath) !== dir) {
        throw new Error(`Organisation id ${JSON.stringify(orgId)} did not resolve inside ${dir}.`);
    }
    return fullPath;
}

/**
 * Asserts that a path is a regular file inside the orgs directory, by looking at the file rather than
 * the name. A symlink is refused outright rather than resolved and allowed, because resolving would
 * let a legal-looking name reach another organisation's data, which is the isolation break this
 * exists to prevent.
 *
 * @param {string} dbPath Result of orgDbPath.
 * @param {string} orgId For the error message.
 * @returns {string|null} The real path of the file, or null when it does not exist yet; absence is
 *   not an error here, and the caller decides whether creating it is allowed.
 * @throws {Error} When the path is a symlink, not a regular file, or resolves outside the store
 *   directory.
 */
export function assertOpenableDatabaseFile(dbPath, orgId) {
    let stats;
    try {
        stats = fs.lstatSync(dbPath);
    } catch (err) {
        if (err.code === 'ENOENT') return null;
        throw err;
    }

    if (stats.isSymbolicLink()) {
        console.error(`[store] refusing to open ${dbPath}: it is a symlink, not a regular file.`);
        throw new Error(
            `Refusing organisation ${orgId}: ${dbPath} is a symlink. ` +
            `The store opens regular files only, so a link cannot redirect one organisation to another's data.`
        );
    }
    if (!stats.isFile()) {
        console.error(`[store] refusing to open ${dbPath}: it is not a regular file.`);
        throw new Error(`Refusing organisation ${orgId}: ${dbPath} is not a regular file.`);
    }

    // Containment against the real directory with the file's real path, which is what the lexical
    // check in orgDbPath cannot do.
    const realFile = fs.realpathSync(dbPath);
    const realDir = orgsDirectoryPath();
    if (path.dirname(realFile) !== realDir) {
        console.error(`[store] refusing to open ${dbPath}: real path ${realFile} is outside ${realDir}.`);
        throw new Error(
            `Refusing organisation ${orgId}: ${dbPath} resolves to ${realFile}, outside the store directory.`
        );
    }
    return realFile;
}

export function adminDbPath() {
    return path.join(storeDir(), ADMIN_DB_NAME);
}

/**
 * Asserts that a path is a regular file directly inside the store directory. The installation-file
 * counterpart of assertOpenableDatabaseFile, checking containment under the store root rather than
 * under orgs/, and refusing a symlink for the same reason: following a link in place of the
 * installation database would place login tokens wherever it points.
 *
 * @param {string} dbPath Result of adminDbPath.
 * @returns {string|null} The real path, or null when it does not exist yet.
 * @throws {Error} When the path is a symlink, not a regular file, or resolves outside the store
 *   directory.
 */
export function assertOpenableAdminDatabaseFile(dbPath) {
    let stats;
    try {
        stats = fs.lstatSync(dbPath);
    } catch (err) {
        if (err.code === 'ENOENT') return null;
        throw err;
    }

    if (stats.isSymbolicLink()) {
        console.error(`[store] refusing to open ${dbPath}: it is a symlink, not a regular file.`);
        throw new Error(
            `Refusing to open ${dbPath}: it is a symlink. The store opens regular files only, ` +
            `so a link cannot redirect the installation database elsewhere.`
        );
    }
    if (!stats.isFile()) {
        console.error(`[store] refusing to open ${dbPath}: it is not a regular file.`);
        throw new Error(`Refusing to open ${dbPath}: it is not a regular file.`);
    }

    // Containment against the real store directory with the file's real path.
    const realFile = fs.realpathSync(dbPath);
    const realDir = fs.realpathSync(storeDir());
    if (path.dirname(realFile) !== realDir) {
        console.error(`[store] refusing to open ${dbPath}: real path ${realFile} is outside ${realDir}.`);
        throw new Error(
            `Refusing to open ${dbPath}: it resolves to ${realFile}, outside the store directory.`
        );
    }
    return realFile;
}

/**
 * Asserts that the store root is still the directory resolved at startup: the counterpart of
 * assertOrgsDirectoryUnchanged for the installation file, which lives directly under the store root
 * rather than under orgs/. Without it, swapping STORE_DIR for a symlink after startup would redirect
 * where admin.db and the organisation directories are written, and the orgs check alone would not
 * notice because it compares the orgs path, which would move with the root.
 *
 * The root is resolved once and compared thereafter, so a store legitimately mounted through a
 * symlink still works.
 *
 * @throws {Error} When the store root no longer resolves to the path first seen.
 */
let resolvedStoreDir = null;

export function assertStoreDirUnchanged() {
    const candidate = storeDir();

    if (resolvedStoreDir === null) {
        fs.mkdirSync(candidate, { recursive: true });
        resolvedStoreDir = fs.realpathSync(candidate);
        return;
    }

    let current;
    try {
        current = fs.realpathSync(candidate);
    } catch (err) {
        throw new Error(
            `The store directory ${candidate} can no longer be resolved (${err.code || err.message}). ` +
            `It was ${resolvedStoreDir} when the store started. Refusing to open a database.`
        );
    }

    if (current !== resolvedStoreDir) {
        console.error(
            `[store] refusing to open a database: ${candidate} now resolves to ${current}, ` +
            `but it resolved to ${resolvedStoreDir} when the store started.`
        );
        throw new Error(
            `The store directory changed underneath the store: ${candidate} now resolves to ${current}, ` +
            `but resolved to ${resolvedStoreDir} at startup. Refusing to write, because following the ` +
            `new target would place data outside the store.`
        );
    }
}

/**
 * Organisation ids present on disk, from the file names in the orgs directory. Only regular files are
 * listed, because a symlink named like an organisation is the isolation break and an admin overview
 * must not count it as a tenant that could legitimately be opened.
 *
 * @returns {string[]} Sorted organisation ids.
 */
export function listOrganisationFileIds() {
    const dir = orgsDirectoryPath();
    if (!fs.existsSync(dir)) return [];

    const ids = [];
    for (const name of fs.readdirSync(dir)) {
        if (!name.endsWith(DB_SUFFIX)) continue;

        const id = name.slice(0, -DB_SUFFIX.length);
        if (!ORG_ID_PATTERN.test(id)) {
            console.warn(`[store] ignoring unrecognised entry in ${dir}: ${name}`);
            continue;
        }

        const stats = fs.lstatSync(path.join(dir, name));
        if (!stats.isFile()) {
            console.warn(`[store] ignoring ${path.join(dir, name)}: not a regular file.`);
            continue;
        }
        ids.push(id);
    }
    return ids.sort();
}
